export type MonthTick = { at: number; label: string | null };

/**
 * Month lines across [start, end], as fractions 0..1 of the width, with a label on the first month
 * and on every January ("Sep 2026"; others "Oct"). Dense scales label only every 2nd/3rd/6th month.
 */
export function monthTicks(start: Date, end: Date, widthPt: number): MonthTick[] {
  const span = Math.max(1, end.getTime() - start.getTime());
  const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  const first = new Date(Date.UTC(start.getUTCFullYear(), start.getUTCMonth(), 1));
  const months: Date[] = [];
  for (let d = first; d.getTime() <= end.getTime(); d = new Date(Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + 1, 1))) {
    months.push(d);
    if (months.length > 240) break;
  }
  const perMonth = widthPt / Math.max(1, months.length);
  const step = perMonth >= 44 ? 1 : perMonth >= 22 ? 2 : perMonth >= 14 ? 3 : 6;
  const ticks: MonthTick[] = [];
  let lastYear: number | null = null;
  months.forEach((date, index) => {
    if (index % step !== 0) return;
    // The year goes on the first label and wherever the year changes (so every January is marked,
    // even when a crowded scale skips the month itself).
    const year = date.getUTCFullYear();
    const withYear = lastYear === null || year !== lastYear || date.getUTCMonth() === 0;
    lastYear = year;
    ticks.push({
      at: (date.getTime() - start.getTime()) / span,
      label: withYear ? `${MONTHS[date.getUTCMonth()]} ${year}` : MONTHS[date.getUTCMonth()],
    });
  });
  return ticks;
}

/** The drawn scale: whole months, so every tick sits inside it. Null when there is nothing to draw. */
export function axisRange(data: ReportData): { start: Date; end: Date } | null {
  const { rangeStart, rangeEnd } = data.timeline;
  if (!rangeStart || !rangeEnd) return null;
  const start = new Date(Date.UTC(rangeStart.getUTCFullYear(), rangeStart.getUTCMonth(), 1));
  const end = new Date(Date.UTC(rangeEnd.getUTCFullYear(), rangeEnd.getUTCMonth() + 1, 1));
  return { start, end };
}
