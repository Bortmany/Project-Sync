// The report's page plan: which page holds what. Pure (no library, no I/O), so the PDF and the
// PowerPoint are guaranteed to say the same things in the same order, and so it can be tested.
//
// Units are points. The two renderers hand in their own page size; everything else follows from it.
// A main task and its discipline tasks are never split across pages, and a heading is never left
// alone at the bottom of a page.

import { reportDate, type ReportData, type ReportLateItem, type ReportMissingDoc, type ReportTimelineDiscipline, type ReportTimelineMainTask } from "@/server/services/report";

export type Geometry = {
  pageW: number;
  pageH: number;
  margin: number;
  /** Body and table text size: 12 in the PDF, 14 in the PowerPoint. */
  bodyFont: number;
};

/** Most discipline bars shown under one main task; the rest are "+N more". */
export const MAX_DISCIPLINE_BARS = 6;

export const FOOTER_TEXT = (data: ReportData): string =>
  `Generated by Tielora from live project data on ${reportDate(data.generatedAt)}.`;

const plural = (n: number, one: string, many = `${one}s`): string => `${n} ${n === 1 ? one : many}`;

/** The one line on the cover: both late kinds named, zeros kept. */
export function coverLine(data: ReportData): string {
  return (
    `${plural(data.late.main, "main task")} and ${plural(data.late.discipline, "discipline task")} late` +
    ` · ${data.blocked} blocked · ${data.documents.missing} required ${data.documents.missing === 1 ? "document" : "documents"} missing`
  );
}

/** "Construction is locked, waiting on FEED, which still has 9 main tasks open." */
export function lockedSentence(phase: { name: string; waitingOn: string | null; openTaskCount: number }): string {
  return `${phase.name} is locked, waiting on ${phase.waitingOn ?? "earlier work"}, which still has ${plural(phase.openTaskCount, "main task")} open.`;
}

export function daysLateText(days: number): string {
  return `${days} d`;
}

